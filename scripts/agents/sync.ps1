<#
.SYNOPSIS
    Generates the agent files of each tool from one source.

.DESCRIPTION
    Reads stacks.psd1 (models, roles, permissions) and roles/*.md (role text),
    and writes .opencode/agents/, .claude/agents/, and .github/agents/. Edit the
    source and run this; do not edit the generated files.

    It overwrites only files this source generates. A generated file it no
    longer produces is reported, not deleted. With -Check it writes nothing and
    fails if any file differs or is stale.

.EXAMPLE
    ./scripts/agents/sync.ps1
    Regenerate every agent file.

.EXAMPLE
    ./scripts/agents/sync.ps1 -Check
    Fail if a generated file has drifted from the source.
#>
[CmdletBinding()]
param(
    # Write nothing; exit 1 if any generated file is missing, different, or stale.
    [switch]$Check
)

$ErrorActionPreference = 'Stop'
$root = Resolve-Path (Join-Path $PSScriptRoot '../..')
$source = Import-PowerShellDataFile (Join-Path $PSScriptRoot 'stacks.psd1')
$header = '# Generated by scripts/agents/sync.ps1. Edit the source there.'

function Get-Body([hashtable]$Role, [scriptblock]$AgentName) {
    $text = Get-Content -Raw (Join-Path $PSScriptRoot "roles/$($Role.Body).md")
    foreach ($name in $source.Roles.Keys) {
        $text = $text.Replace("{$name}", (& $AgentName $name))
    }
    $text -replace "`r`n", "`n"
}

function Format-Quoted([string]$Text) {
    '"' + $Text.Replace('\', '\\').Replace('"', '\"') + '"'
}

function Join-File([string[]]$Frontmatter, [string]$Body) {
    (@('---', $header) + $Frontmatter + '---') -join "`n" | ForEach-Object { "$_`n$Body" }
}

function Get-OpenCodePermission([string]$Access, [string]$Family) {
    $ask = $source.AskBash | ForEach-Object { "    $(Format-Quoted $_): ask" }
    $noCommit = @('    "git commit *": deny', '    "git push *": deny')
    switch ($Access) {
        'lead' {
            @('  task:', '    "*": deny', "    `"$Family-*`": allow", '  bash:') + $ask
        }
        'read' {
            @('  edit: deny', '  task: deny', '  bash: deny', '  "rust_*": deny') +
            ($source.ReadOnlyRustTools | ForEach-Object { "  $(Format-Quoted $_): allow" })
        }
        'write' { @('  edit: allow', '  task: deny', '  bash:') + $ask + $noCommit }
        'verify' { @('  edit: ask', '  task: deny', '  bash:') + $ask + $noCommit }
    }
}

function Get-OpenCodeFiles {
    foreach ($family in $source.OpenCode.Keys) {
        $stack = $source.OpenCode[$family]
        foreach ($roleName in $source.Roles.Keys) {
            $role = $source.Roles[$roleName]
            $tier = $stack[$role.Tier]
            $front = @(
                "description: $(Format-Quoted "$($role.Description) ($($stack.Label) stack, tier $($role.Tier).)")"
                "mode: $(if ($role.Access -eq 'lead') { 'primary' } else { 'subagent' })"
            )
            if ($tier.Model) { $front += "model: $($tier.Model)" }
            if ($tier.Variant) { $front += "variant: $($tier.Variant)" }
            $front += 'permission:'
            $front += Get-OpenCodePermission $role.Access $family
            $name = { param($n) "$family-$n" }.GetNewClosure()
            @{
                Path    = ".opencode/agents/$family-$roleName.md"
                Content = Join-File $front (Get-Body $role $name)
            }
        }
    }
}

function Get-ClaudeCodeFiles {
    foreach ($roleName in $source.Roles.Keys) {
        $role = $source.Roles[$roleName]
        $tier = $source.ClaudeCode[$role.Tier]
        $fileName = if ($role.Access -eq 'lead') { 'lead' } else { $roleName }
        $subagents = ($source.Roles.Keys | Where-Object { $source.Roles[$_].Access -ne 'lead' } | Sort-Object) -join ', '
        $front = @(
            "name: $fileName"
            "description: $(Format-Quoted "$($role.Description) (Tier $($role.Tier).)")"
            "model: $($tier.Model)"
            "effort: $($tier.Effort)"
        )
        $front += switch ($role.Access) {
            'lead' { "tools: Agent($subagents), Read, Grep, Glob, Edit, Write, Bash, TodoWrite, WebFetch, WebSearch" }
            'read' { 'tools: Read, Grep, Glob' }
            'write' { 'disallowedTools: Agent' }
            'verify' { 'disallowedTools: Agent, Edit, Write, NotebookEdit' }
        }
        $name = { param($n) if ($n -eq 'main') { 'lead' } else { $n } }
        @{
            Path    = ".claude/agents/$fileName.md"
            Content = Join-File $front (Get-Body $role $name)
        }
    }
}

function Get-CopilotFiles {
    foreach ($roleName in $source.Roles.Keys) {
        $role = $source.Roles[$roleName]
        $tier = $source.Copilot[$role.Tier]
        $fileName = if ($role.Access -eq 'lead') { 'lead' } else { $roleName }
        $tools = switch ($role.Access) {
            'lead' { 'read, search, edit, execute, agent, web, todo' }
            'read' { 'read, search' }
            'write' { 'read, search, edit, execute' }
            'verify' { 'read, search, execute' }
        }
        $front = @("description: $(Format-Quoted "$($role.Description) (Tier $($role.Tier).)")")
        if ($tier.Model) { $front += "model: $($tier.Model)" }
        $front += @("tools: [$tools]", 'strict-tools-list: true', 'include-custom-instructions: true')
        $name = { param($n) if ($n -eq 'main') { 'lead' } else { $n } }
        @{
            Path    = ".github/agents/$fileName.agent.md"
            Content = Join-File $front (Get-Body $role $name)
        }
    }
}

$files = @(Get-OpenCodeFiles) + @(Get-ClaudeCodeFiles) + @(Get-CopilotFiles)
$problems = @()

foreach ($file in $files) {
    $path = Join-Path $root $file.Path
    $current = if (Test-Path $path) { (Get-Content -Raw $path) -replace "`r`n", "`n" }
    if ($current -ceq $file.Content) { continue }
    if ($Check) {
        $problems += "differs or missing: $($file.Path)"
    } else {
        New-Item -ItemType Directory -Force (Split-Path $path) | Out-Null
        [IO.File]::WriteAllText($path, $file.Content, [Text.UTF8Encoding]::new($false))
        Write-Output "wrote $($file.Path)"
    }
}

$expected = $files | ForEach-Object { [IO.Path]::GetFullPath((Join-Path $root $_.Path)) }
foreach ($dir in '.opencode/agents', '.claude/agents', '.github/agents') {
    $full = Join-Path $root $dir
    if (-not (Test-Path $full)) { continue }
    foreach ($found in Get-ChildItem $full -File) {
        if ($found.FullName -notin $expected) {
            $problems += "not generated by this source: $dir/$($found.Name)"
        }
    }
}

$problems | ForEach-Object { Write-Warning $_ }
if ($Check -and $problems) { exit 1 }
Write-Output "$($files.Count) agent files checked"
